-- إضافة حالة superseded إلى core.quotation_status — قرار المراجعة (§10 بند 2)
--
-- القاعدة: إذا أُنشئت نسخة جديدة بينما توجد نسخة سابقة (مسودة أو مرسلة)،
-- تُختم السابقة superseded ذريًا — فلا يمكن وجود نسختين قابلتين للقرار.
--
-- سياسة الـenum المصادق عليها (DECISIONS §8): إضافة قيم فقط، ولا يجوز استعمال
-- القيمة الجديدة في نفس الترحيل الذي أضافها (قيد PostgreSQL على المعاملة
-- الواحدة) — لذلك هذا الملف منفصل عن ترحيل القيود الذي يستعملها.
-- ============================================================================

alter type core.quotation_status add value if not exists 'superseded';
