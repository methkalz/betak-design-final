/**
 * عقد العرض المالي - قاعدة «لا أغورة» عند آخر نقطة عرض.
 *
 * M21: عدّاد المبيعات كان يكبر خاناته أثناء الحركة ثم ينكمش، لأن القيم
 * الوسيطة كسرية وكانت تُعرض بمنزلتين. هذه الاختبارات تثبّت أن الكسر لا
 * يظهر أبدًا مهما كان مصدر القيمة. تُشغَّل مع `bun test`.
 */
import { test, expect } from 'bun:test';

import { money } from './format';

const strip = (s: string) => s.replace(/[⁦⁩]/g, '');

test('المبالغ الصحيحة تُعرض كما هي بفواصل الآلاف', () => {
  expect(strip(money(124000))).toBe('₪1,240');
  expect(strip(money(0))).toBe('₪0');
});

test('القيم الكسرية العابرة (عدّاد متحرك) تُبتر ولا تُعرض بمنازل', () => {
  // 11,543.27 شيكل أثناء طيران العدّاد - كانت تُعرض بخانتين إضافيتين
  expect(strip(money(1154327))).toBe('₪11,543');
  // البتر لا التقريب: 1,999.5 لا تصير 2,000
  expect(strip(money(199950))).toBe('₪1,999');
});

test('السالب يُبتر نحو الصفر فلا يُضخَّم', () => {
  expect(strip(money(-199950))).toBe('₪-1,999');
});

test('المختصر k يعمل على القيمة المبتورة', () => {
  expect(strip(money(1250000, { compact: true }))).toBe('₪12.5k');
  expect(strip(money(1200000, { compact: true }))).toBe('₪12k');
});
