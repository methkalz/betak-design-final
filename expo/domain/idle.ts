/**
 * الخمول على الأجهزة المشتركة - منطقٌ نقيّ يُفحَص بالوحدة.
 *
 * **لماذا**: على الهاتف الجلسة مشفَّرة ومقفولة بقفل الجهاز نفسه؛ الهاتف ملكُ
 * صاحبه. أمّا على مكتبٍ في المعرض يفتحه أكثر من موظّف، فمتصفّحٌ متروكٌ مفتوحًا
 * يعني حسابًا مفتوحًا - وقد يكون حساب أدمن يرى التكلفة والأرباح. فتنتهي
 * الجلسة بعد خمولٍ طويل بدل أن تبقى إلى الأبد.
 *
 * القياس بالطابع الزمني لا بمؤقّتٍ متراكم: المتصفّحات **تخنق المؤقّتات في
 * الألسنة الخلفية** (ثانيةً واحدة كلّ دقيقة أحيانًا)، فمؤقّتٌ لثلاثين دقيقة
 * قد لا ينضج إلا بعد ساعات. أمّا فرقُ طابعين فصادقٌ مهما نام اللسان.
 */

/** حدّ الخمول: نصف ساعة. رقمٌ واحد يُغيَّر هنا فيسري على التطبيق كلّه. */
export const IDLE_LIMIT_MS = 30 * 60 * 1000;

/** كم يفصلنا عن انتهاء الجلسة (بالملّي)، صفرٌ إن انتهت. */
export function idleRemainingMs(
  lastActivityAt: number,
  now: number,
  limitMs: number = IDLE_LIMIT_MS,
): number {
  return Math.max(0, lastActivityAt + limitMs - now);
}

/**
 * هل انتهت الجلسة خمولًا؟
 *
 * ساعةُ الجهاز قد ترجع للخلف (مزامنة زمنية، أو تغيير المستخدم للتوقيت)،
 * فيصير `now < lastActivityAt`. عندها **لا نُخرج** - الأمان لا يبرّر طردَ
 * مستخدمٍ نشِط بسبب ساعة، والحدّ سيُقاس من جديد عند أوّل نشاط.
 */
export function isIdleExpired(
  lastActivityAt: number,
  now: number,
  limitMs: number = IDLE_LIMIT_MS,
): boolean {
  if (now < lastActivityAt) return false;
  return now - lastActivityAt >= limitMs;
}
