/**
 * معجم الوثيقة - ترجمة تظهر أمام زبونٍ يوقّع، فخطؤها ليس خطأ عرض.
 */
import { expect, test } from 'bun:test';

import { glossarySize, translateTerm } from './quoteGlossary';

const he = (s: string) => translateTerm(s, 'he');

test('العربية تعود كما هي - لا ترجمة إلى الذات', () => {
  for (const s of ['الصالون', 'الشباك الأول', 'مثقال زيدان', '']) {
    expect(translateTerm(s, 'ar')).toBe(s);
  }
});

test('أسماء الغرف المقترَحة السبعة كلّها تُترجم', () => {
  expect(he('الصالون')).toBe('הסלון');
  expect(he('غرفة الأهل')).toBe('חדר ההורים');
  expect(he('غرفة الأولاد')).toBe('חדר הילדים');
  expect(he('غرفة البنات')).toBe('חדר הבנות');
  expect(he('غرفة الضيوف')).toBe('חדר האורחים');
  expect(he('المطبخ')).toBe('המטבח');
  expect(he('المكتب')).toBe('המשרד');
});

test('أسماء الشبابيك المولَّدة ترتيبًا - العشرة', () => {
  const ORD = [
    'الأول', 'الثاني', 'الثالث', 'الرابع', 'الخامس',
    'السادس', 'السابع', 'الثامن', 'التاسع', 'العاشر',
  ];
  const EXPECT = [
    'הראשון', 'השני', 'השלישי', 'הרביעי', 'החמישי',
    'השישי', 'השביעי', 'השמיני', 'התשיעי', 'העשירי',
  ];
  ORD.forEach((o, k) => {
    expect(he(`الشباك ${o}`)).toBe(`החלון ${EXPECT[k]}`);
  });
});

/**
 * ★ الترجمة كلمةً كلمة سليمةٌ هنا لأن اللغتين ساميّتان: الإضافة والصفة بنفس
 * الترتيب. هذه أسماءٌ حقيقيّة من بذرة المشروع لا أمثلةٌ مخترَعة.
 */
test('★ أسماءٌ مركّبة من بيانات حقيقية تخرج عبريّةً صحيحة', () => {
  expect(he('صالون الضيوف')).toBe('סלון האורחים');
  expect(he('غرفة النوم الرئيسية')).toBe('חדר השינה הראשי');
  expect(he('شباك غرفة النوم')).toBe('חלון חדר השינה');
  expect(he('شباك المطبخ')).toBe('חלון המטבח');
  expect(he('شباك غرفة الأولاد')).toBe('חלון חדר הילדים');
});

test('★ ما لا يعرفه المعجم يمرّ كما هو - لا تشويه أبدًا', () => {
  // اسم شخص: لا يدخل المعجم إطلاقًا فيمرّ حتمًا
  expect(he('مثقال زيدان')).toBe('مثقال زيدان');
  // كلمةٌ معروفة وأخرى مجهولة في نصٍّ واحد: تُترجم المعروفة وتبقى المجهولة
  expect(he('غرفة سناء')).toBe('חדר سناء');
  // نصٌّ لاتينيّ أو رقميّ لا يُمسّ
  expect(he('Room 3')).toBe('Room 3');
});

test('الفواصل والمسافات تبقى كما هي - لا يضيع شَرطةٌ ولا فراغ', () => {
  expect(he('الصالون - الشباك الأول')).toBe('הסלון - החלון הראשון');
  expect(he('المطبخ، المكتب')).toBe('המטבח، המשרד');
  expect(he('  المطبخ  ')).toBe('  המטבח  ');
});

test('المدينة تُترجم بصيغتيها', () => {
  expect(he('كفرمندا')).toBe('כפר מנדא');
  expect(he('كفر مندا')).toBe('כפר מנדא');
});

test('نصٌّ فارغ أو غيابٌ لا يرمي', () => {
  expect(he('')).toBe('');
  expect(translateTerm('', 'ar')).toBe('');
});

test('المعجم غيرُ فارغ - حارسٌ ضدّ حذفٍ عرَضيّ', () => {
  expect(glossarySize).toBeGreaterThan(50);
});
