/** الفواصل التي نقسم عليها ونُعيدها كما هي - فلا يضيع شَرطةٌ ولا مسافة. */
const SPLIT = /(\s+|-|،|,|\/|\(|\))/;

/**
 * يترجم نصًّا يولّده التطبيق إلى لغة الوثيقة.
 *
 * العربية تُعيده كما هو (لا ترجمة إلى الذات). والعبرية تترجم ما تعرفه
 * وتُبقي ما لا تعرفه - فلا تشويه أبدًا.
 */
export function translateTerm(text: string, lang: QuoteLang): string {
  if (lang !== 'he' || !text) return text;
  return text
    .split(SPLIT)
    .map((part) => HE[part] ?? part)
    .join('');
}

